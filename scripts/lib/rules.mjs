// Renders rules/*.md into the per-tool instruction files each AI coding
// environment reads, and into DECORATOR.md, the detail those files point to.
//
// This lives in a library because two callers need it against two different
// output roots: scripts/compile-rules.mjs regenerates the copies committed to
// this repository, and bin/cli.mjs writes them into a consumer's project. A
// second implementation would drift from the first, which is the failure this
// kit exists to prevent.

export const GENERATED_NOTE =
  "<!-- Generated by scripts/compile-rules.mjs from rules/. Do not edit directly. -->";

// Where the rule files send an agent for detail that only some tasks need.
//
// Claude Code loads all of CLAUDE.md at the start of every session, and warns
// once one passes MEMORY_FILE_WARN_CHARS. An `@DECORATOR.md` import would not
// help: an imported file loads at launch too, and counts toward the same
// warnings. So the rule files keep what must hold in every session, and a
// section that also carries measurements or a procedure for one kind of task
// sends the rest here, leaving a line that names the task. Nothing imports this
// file. An agent reads it when a rule file tells it to.
export const ON_DEMAND_FILE = "DECORATOR.md";

// The size at which Claude Code reports "Large CLAUDE.md will impact
// performance": 40,000 characters, or more on a model with a larger context
// window. The kit's own rules stay well under it — test/rules.test.mjs holds
// them to a budget — so that a project's canvas rules have room.
export const MEMORY_FILE_WARN_CHARS = 40_000;

// A line of its own, outside a code fence, that moves the rest of its block to
// DECORATOR.md:
//
//   <!-- on-demand: before you copy `two-column.html` or `three-column.html` -->
//
// The block is the `## ` section the marker sits in, or the whole rule when it
// sits above the first section. The rule files keep what comes above the marker
// and, in place of the rest, "Before you copy …, read this section in full in
// `DECORATOR.md`." DECORATOR.md gets the block whole. So write the trigger as
// the task that needs the rest, starting "before you" or "when".
const ON_DEMAND_MARKER = /^<!--\s*on-demand\b(.*?)-->\s*$/;
const ON_DEMAND_START = /^<!--\s*on-demand\b/;

