export function stripFrontmatter(source) {
  const match = /^---\n([\s\S]*?)\n---\n?/.exec(source);
  if (!match) return { data: {}, body: source.trim() };
  const data = {};
  for (const line of match[1].split("\n")) {
    const separator = line.indexOf(":");
    if (separator === -1) continue;
    data[line.slice(0, separator).trim()] = line.slice(separator + 1).trim();
  }
  return { data, body: source.slice(match[0].length).trim() };
}

/**
 * For each line, whether it belongs to a fenced code block, fences included.
 *
 * A `# comment` in a shell sample is not a heading, and a marker in a code
 * sample is not a marker. Project canvas rules are written by whoever drops a
 * file in, code samples included.
 */
function fencedLines(lines) {
  let fence = null;
  return lines.map((line) => {
    const marker = /^ {0,3}(`{3,}|~{3,})/.exec(line);
    if (marker) {
      if (!fence) fence = marker[1];
      else if (marker[1][0] === fence[0] && marker[1].length >= fence.length) fence = null;
      return true;
    }
    return fence !== null;
  });
}

/** Push every heading in a rule body down `levels` so it nests under its title. */
export function demoteHeadings(body, levels = 1) {
  const lines = body.split("\n");
  const fenced = fencedLines(lines);
  return lines
    .map((line, index) => {
      if (fenced[index]) return line;
      const heading = /^(#{1,6}) /.exec(line);
      if (!heading) return line;
      return `${"#".repeat(Math.min(heading[1].length + levels, 6))} ${line.slice(heading[0].length)}`;
    })
    .join("\n");
}

function hasOnDemandMarker(body) {
  const lines = body.split("\n");
  const fenced = fencedLines(lines);
  return lines.some((line, index) => !fenced[index] && ON_DEMAND_START.test(line));
}

/**
 * Split a rule body into its preamble and its `## ` sections, each divided at
 * its on-demand marker, if it has one.
 *
 * Each block carries `core`, the text above the marker (all of it, without
 * one), `full`, the whole block less the marker line, and `trigger`, the
 * marker's text or null.
 */
function parseRule(filename, title, body) {
  const lines = body.split("\n");
  const fenced = fencedLines(lines);
  const blocks = [{ heading: null, lines: [], trigger: null, split: 0 }];

  lines.forEach((line, index) => {
    if (!fenced[index] && line.startsWith("## ")) {
      blocks.push({ heading: line.slice(3).trim(), lines: [], trigger: null, split: 0 });
      return;
    }
    const block = blocks.at(-1);
    if (!fenced[index] && ON_DEMAND_START.test(line)) {
      const where = block.heading ? `rules/${filename}, "${block.heading}"` : `rules/${filename}`;
      const trigger = /^:\s*(\S.*?)\.?\s*$/.exec(ON_DEMAND_MARKER.exec(line)?.[1] ?? "")?.[1];
      if (!trigger) {
        throw new Error(`${where}: write an on-demand marker on one line, as <!-- on-demand: before you … -->.`);
      }
      if (block.trigger) throw new Error(`${where} has two on-demand markers. A block can move to ${ON_DEMAND_FILE} once.`);
      block.trigger = trigger;
      block.split = block.lines.length;
      return;
    }
    block.lines.push(line);
  });

  const text = (part) => part.join("\n").trim();
  const [preamble, ...sections] = blocks.map((block) => {
    const split = block.trigger ? block.split : block.lines.length;
    const core = text(block.lines.slice(0, split));
    const rest = text(block.lines.slice(split));
    return { heading: block.heading, trigger: block.trigger, core, full: [core, rest].filter(Boolean).join("\n\n") };
  });
  if (preamble.trigger && sections.some((section) => section.trigger)) {
    throw new Error(
      `rules/${filename} moves the whole rule to ${ON_DEMAND_FILE} above its first section, so none of its sections can carry a marker of its own.`,
    );
  }
  const rule = { filename, title, preamble, sections };
  return { ...rule, body: fullBody(rule) };
}

/** Headings in DECORATOR.md that a rule file sends agents to by name. */
function movedHeadings(rule) {
  if (rule.preamble.trigger) return [rule.title];
  return rule.sections.filter((section) => section.trigger).map((section) => section.heading);
}

export async function readRules(rulesDir) {
  const filenames = (await readdir(rulesDir)).filter((name) => name.endsWith(".md")).sort();
  if (!filenames.length) throw new Error(`${rulesDir} contains no markdown files.`);
  const rules = [];
  const moved = new Map();
  for (const filename of filenames) {
    const { data, body } = stripFrontmatter(await readFile(path.join(rulesDir, filename), "utf8"));
    if (!data.title) throw new Error(`rules/${filename} is missing a frontmatter title.`);
    const rule = parseRule(filename, data.title, body);
    for (const heading of movedHeadings(rule)) {
      if (moved.has(heading)) {
        throw new Error(
          `rules/${moved.get(heading)} and rules/${filename} both move "${heading}" to ${ON_DEMAND_FILE}, where agents look it up by name. Rename one.`,
        );
      }
      moved.set(heading, filename);
    }
    rules.push(rule);
  }
  return rules;
}

function missingIsEmpty(error) {
  if (error.code === "ENOENT") return [];
  throw error;
}

/**
 * Title and body of a Markdown file a project's developers dropped in. Unlike
 * rules/, frontmatter is optional: the title is a frontmatter `title:`, else a
 * leading `# Heading` (which is then removed from the body), else
 * `fallbackTitle`.
 */
function parseDroppedMarkdown(source, fallbackTitle) {
  const parsed = stripFrontmatter(source.replace(/\r\n?/g, "\n"));
  let body = parsed.body;
  let title = parsed.data.title?.replace(/^(["'])(.*)\1$/, "$2");
  const heading = /^# (.+)(?:\n|$)/.exec(body);
  if (!title && heading) {
    title = heading[1].trim();
    body = body.slice(heading[0].length).trim();
  }
  return { title: title || fallbackTitle, body };
}

/**
 * Read a project's own canvas rules: every top-level `*.md` in `directory`
 * except README.md, in filename order. A missing directory means no rules.
 */
export async function readCanvasRules(directory) {
  const entries = await readdir(directory, { withFileTypes: true }).catch(missingIsEmpty);
  const filenames = entries
    .map((entry) => entry.isFile() && entry.name)
    .filter((name) => name && !name.startsWith(".") && name.toLowerCase().endsWith(".md"))
    .filter((name) => name.toLowerCase() !== "readme.md")
    .sort();

  const rules = [];
  for (const filename of filenames) {
    const source = await readFile(path.join(directory, filename), "utf8");
    const { title, body } = parseDroppedMarkdown(source, filename.replace(/\.md$/i, ""));
    if (!body) continue;
    // Honoring it would put a project's rule where an agent reads it only on
    // cue. Ignoring it would leave the author believing it worked.
    if (hasOnDemandMarker(body)) {
      throw new Error(
        `${CANVAS_RULES_DIR}/${filename}: on-demand markers work only in the kit's own rules. A project's canvas rules load in full in every session, so keep in them only what must hold in every session.`,
      );
    }
    rules.push({ filename, title, body });
  }
  return rules;
}

/**
 * Read a project's component libraries: one entry per folder in `directory`,
 * in name order, carrying that folder's README.md. A folder with no README is
 * still listed, so agents know the library exists and ask before using it.
 */
export async function readCanvasComponents(directory) {
  const entries = await readdir(directory, { withFileTypes: true }).catch(missingIsEmpty);
  const folders = entries
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith(".") && entry.name !== "node_modules")
    .map((entry) => entry.name)
    .sort();

  const libraries = [];
  for (const folder of folders) {
    const readme = (await readdir(path.join(directory, folder))).find((name) => name.toLowerCase() === "readme.md");
    const source = readme ? await readFile(path.join(directory, folder, readme), "utf8") : "";
    libraries.push({ folder, readme, ...parseDroppedMarkdown(source, folder) });
  }
  return libraries;
}

function pointer(trigger) {
  return `**${trigger[0].toUpperCase()}${trigger.slice(1)}, read this section in full in \`${ON_DEMAND_FILE}\`.**`;
}

function section(heading, ...parts) {
  return [`## ${heading}`, ...parts].filter(Boolean).join("\n\n");
}

function fullBody(rule) {
  return [rule.preamble.full, ...rule.sections.map((entry) => section(entry.heading, entry.full))]
    .filter(Boolean)
    .join("\n\n");
}

/** What a rule contributes to the rule files: everything above its markers. */
function coreBody(rule) {
  if (rule.preamble.trigger) return [rule.preamble.core, pointer(rule.preamble.trigger)].filter(Boolean).join("\n\n");
  const sections = rule.sections.map((entry) => section(entry.heading, entry.core, entry.trigger && pointer(entry.trigger)));
  return [rule.preamble.core, ...sections].filter(Boolean).join("\n\n");
}

/** What a rule contributes to DECORATOR.md: every block it marks, whole. */
function onDemandBody(rule) {
  if (rule.preamble.trigger) return rule.body;
  return rule.sections
    .filter((entry) => entry.trigger)
    .map((entry) => section(entry.heading, entry.full))
    .join("\n\n");
}

function renderCanvasRules(canvasRules) {
  const sections = canvasRules.map(
    (rule) =>
      `### ${rule.title}\n\n_From \`${CANVAS_RULES_DIR}/${rule.filename}\`._\n\n${demoteHeadings(rule.body, 2)}`,
  );
  return [`## Project canvas rules`, CANVAS_RULES_PREAMBLE, ...sections].join("\n\n");
}

function librarySource(library) {
  const location = `${CANVAS_COMPONENTS_DIR}/${library.folder}/`;
  return library.readme ? `_From \`${location}${library.readme}\`._` : `_Folder \`${location}\`._`;
}

function renderComponentLibraries(libraries) {
  const sections = libraries.map(
    (library) => `### ${library.title}\n\n${librarySource(library)}\n\n${library.body ? LIBRARY_POINTER : NO_LIBRARY_NOTES}`,
  );
  return ["## Project component libraries", COMPONENT_LIBRARIES_PREAMBLE, ...sections].join("\n\n");
}

function renderLibraryReference(libraries) {
  const sections = libraries.map(
    (library) => `### ${library.title}\n\n${librarySource(library)}\n\n${demoteHeadings(library.body, 2)}`,
  );
  return ["## Project component libraries", LIBRARY_REFERENCE_PREAMBLE, ...sections].join("\n\n");
}

function renderFile(note, heading, intros, sections) {
  return [note, "", `# ${heading}`, "", ...intros.flatMap((intro) => [intro, ""]), "---", "", sections.join("\n\n---\n\n"), ""].join(
    "\n",
  );
}

function renderRuleFile(target, rules, note, projectSections) {
  const sections = rules.map((rule) => `## ${rule.title}\n\n${demoteHeadings(coreBody(rule))}`);
  return renderFile(note, target.heading, [target.intro, ON_DEMAND_NOTE], [...sections, ...projectSections]);
}

function renderOnDemandFile(rules, note, componentLibraries) {
  const sections = rules
    .map((rule) => ({ title: rule.title, body: onDemandBody(rule) }))
    .filter((rule) => rule.body)
    .map((rule) => `## ${rule.title}\n\n${demoteHeadings(rule.body)}`);
  const documented = componentLibraries.filter((library) => library.body);
  if (documented.length) sections.push(renderLibraryReference(documented));
  return renderFile(note, ON_DEMAND_TARGET.heading, [ON_DEMAND_TARGET.intro], sections);
}

/**
 * Render every generated file as a Map of repo-relative path to contents.
 *
 * @param {object}   options
 * @param {string}   options.rulesDir      directory holding rules/*.md
 * @param {string}  [options.note]         the generated-by comment to stamp in.
 *   Consumer projects pass a version-stamped note so `check` fails after the kit
 *   is upgraded; this repository's own copies keep the unversioned default, or a
 *   version bump would dirty five committed files and destabilize `npm test`.
 * @param {string[]}[options.exclude]      target filenames to skip. `add` passes
 *   ["AGENTS.md"] — see bin/cli.mjs for why that one is never written.
 * @param {boolean} [options.references]   also render the exported skill pages.
 * @param {string}  [options.canvasRulesDir] a consumer project's canvas-rules/
 *   directory, compiled in after the kit's rules. This repository's own copies
 *   pass nothing: the kit has no canvas of its own.
 * @param {string}  [options.canvasComponentsDir] a consumer project's
 *   canvas-components/ directory, whose libraries compile in likewise.
 *
 * `projectChars` says how many characters of each rule file the project's own
 * canvas-rules/ and canvas-components/ sections take up.
 */
export async function renderRuleFiles({
  rulesDir,
  note = GENERATED_NOTE,
  exclude = [],
  references = false,
  canvasRulesDir,
  canvasComponentsDir,
} = {}) {
  const rules = await readRules(rulesDir);
  const canvasRules = canvasRulesDir ? await readCanvasRules(canvasRulesDir) : [];
  const componentLibraries = canvasComponentsDir ? await readCanvasComponents(canvasComponentsDir) : [];
  const outputs = new Map();

  // Libraries first: a project canvas rule is the likelier one to name a library.
  const libraries = componentLibraries.length ? renderComponentLibraries(componentLibraries) : "";
  const projectRules = canvasRules.length ? renderCanvasRules(canvasRules) : "";
  const projectSections = [libraries, projectRules].filter(Boolean);

  for (const target of TARGETS) {
    if (exclude.includes(target.file)) continue;
    outputs.set(target.file, renderRuleFile(target, rules, note, projectSections));
  }
  outputs.set(ON_DEMAND_FILE, renderOnDemandFile(rules, note, componentLibraries));

  if (references) {
    for (const [source, destination] of REFERENCE_EXPORTS) {
      const rule = rules.find((entry) => entry.filename === source);
      if (!rule) throw new Error(`REFERENCE_EXPORTS names rules/${source}, which does not exist.`);
      outputs.set(
        path.posix.join("skills/ucsd-decorator/references", destination),
        `${note}\n\n# ${rule.title}\n\n${rule.body}\n`,
      );
    }
  }

  const projectChars = { canvasRules: projectRules.length, componentLibraries: libraries.length };
  return { rules, canvasRules, componentLibraries, outputs, projectChars };
}
