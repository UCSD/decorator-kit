#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { cp, mkdir, readFile, readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { renderRuleFiles } from "../scripts/lib/rules.mjs";

// Installs the UC San Diego Decorator contract into a project.
//
//   init    scaffold a new project: Decorator dependency, rules, skill, CI, hook
//   add     install into an existing project — never writes AGENTS.md
//   sync    refresh the files this kit manages here, after a kit upgrade
//   check   fail if those files are out of date (wire this into CI)
//   drift   report whether the Decorator moved upstream
//   verify  run the chrome integrity gate against this project's markup
//
// No dependencies: this runs via `npx` in a project that has installed nothing.
//
// ── Why `add` exists, and why it will not write AGENTS.md ──────────────────
//
// The kit compiles one rule set into four files, one per tool. Three of those
// names are unambiguous. `AGENTS.md` is not: it is also the conventional name
// for a repository's own agent contract, and a project that already has one has
// something more specific and more important than this kit's generic rules.
//
// tritonai-website is the case in point. Its AGENTS.md is a tracked 18 KB
// project contract, and its CONTRIBUTING.md says outright: "Do not copy
// decorator-kit's AGENTS.md into this repository. Both files carry that name and
// they are different documents." Overwriting it would replace a specific
// contract with a generic one and look like a successful install.
//
// So `add` never emits that filename — not with --force either — and records in
// decorator-kit.json exactly which files it manages, so a later `sync` cannot
// reach a file the install declined to write.

const KIT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const RULES_DIR = path.join(KIT_ROOT, "rules");
const SKILL_SOURCE = path.join(KIT_ROOT, "skills/ucsd-decorator");
const TEMPLATES = path.join(KIT_ROOT, "templates");

const MANIFEST = "decorator-kit.json";
const SKILL_DEST = ".claude/skills/ucsd-decorator";
const PROJECT_CONTRACT = "AGENTS.md";
const DECORATOR_PACKAGE = "ucsd-decorator-v5";
const CLAUDE_SETTINGS = ".claude/settings.json";

// Entries that do not make a directory "an existing project" for `init`.
const GREENFIELD_OK = new Set([
  ".git",
  ".gitignore",
  ".DS_Store",
  "node_modules",
  "package.json",
  "package-lock.json",
  "README.md",
  "LICENSE",
]);

const cwd = process.cwd();
const argv = process.argv.slice(2);
const command = argv.find((entry) => !entry.startsWith("-")) ?? "help";
const has = (name) => argv.includes(`--${name}`);

const kitPackage = JSON.parse(await readFile(path.join(KIT_ROOT, "package.json"), "utf8"));
const VERSION = kitPackage.version;

const NOTE = `<!-- Generated by ucsd-decorator-kit@${VERSION} from rules/. Do not edit directly — run \`npx ucsd-decorator-kit sync\` after upgrading the kit. -->`;

const exists = (target) => stat(target).then(() => true).catch(() => false);
const relative = (target) => path.relative(cwd, target) || ".";

const report = { wrote: [], skipped: [], refused: [], refreshed: [] };

/**
 * Write one file, honoring the never-overwrite rule.
 *
 * `allowContract` decides whether this call may write AGENTS.md. It defaults
 * to `command === "init"` — right for `init` (always allowed) and for `add`
 * (never reaches here for that filename; see below) — but `sync` overrides it
 * per project, from that project's own manifest. A project `add` set up never
 * put AGENTS.md in `manages`, so `renderFor` excludes it before `sync`'s loop
 * ever calls `put`. A project `init` set up did manage it, so `sync` must be
 * able to refresh it same as any other managed file — defaulting this to
 * "only during init" silently made sync unable to ever fix a drifted AGENTS.md
 * on an init'd project, no matter how many times you ran it.
 */
async function put(relativePath, contents, { force = false, allowContract = command === "init" } = {}) {
  if (relativePath === PROJECT_CONTRACT && !allowContract) {
    report.refused.push(relativePath);
    return false;
  }
  const absolute = path.join(cwd, relativePath);
  if ((await exists(absolute)) && !force) {
    const current = await readFile(absolute, "utf8").catch(() => null);
    if (current === contents) return false;
    report.skipped.push(relativePath);
    return false;
  }
  await mkdir(path.dirname(absolute), { recursive: true });
  await writeFile(absolute, contents);
  report.wrote.push(relativePath);
  return true;
}

/** The skill is a published copy of skills/ucsd-decorator, not a file to edit. */
async function publishSkill() {
  const destination = path.join(cwd, SKILL_DEST);
  const existed = await exists(destination);
  await mkdir(path.dirname(destination), { recursive: true });
  await cp(SKILL_SOURCE, destination, {
    recursive: true,
    filter: (entry) => !path.basename(entry).startsWith("."),
  });
  (existed ? report.refreshed : report.wrote).push(`${SKILL_DEST}/`);
}

async function walk(directory, base) {
  const out = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.name.startsWith(".")) continue;
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(absolute, base)));
    else out.push(path.relative(base, absolute).split(path.sep).join("/"));
  }
  return out;
}

async function readManifest() {
  const raw = await readFile(path.join(cwd, MANIFEST), "utf8").catch(() => null);
  if (raw === null) return null;
  try {
    return JSON.parse(raw);
  } catch (error) {
    throw new Error(`${MANIFEST} is not valid JSON: ${error.message}`);
  }
}

async function writeManifest(managed) {
  const previous = await readManifest();
  const manifest = {
    $schema: "https://github.com/UCSD/decorator-kit/contracts/decorator-kit.schema.json",
    kitVersion: VERSION,
    // The one writable region. Everything else on the page is chrome. A project
    // with a different shell — the Antigravity Code Kit uses div#ag-app-canvas —
    // edits this, and the chrome gate reads it from here.
    canvas: previous?.canvas ?? "main#main-content",
    decorator: {
      package: DECORATOR_PACKAGE,
      readFrom: `node_modules/${DECORATOR_PACKAGE}/dist`,
    },
    // Exactly the files this kit owns here. `sync` and `check` operate on this
    // list and nothing else, so a file the install declined to write — AGENTS.md
    // in a project that has its own — can never be reached later.
    manages: managed,
  };
  await writeFile(path.join(cwd, MANIFEST), `${JSON.stringify(manifest, null, 2)}\n`);
  return manifest;
}

async function renderFor(managedOnly) {
  const exclude = managedOnly ? [] : [PROJECT_CONTRACT];
  const { outputs } = await renderRuleFiles({ rulesDir: RULES_DIR, note: NOTE, exclude });
  return outputs;
}

async function addScripts() {
  const packagePath = path.join(cwd, "package.json");
  if (!(await exists(packagePath))) return;
  const manifest = JSON.parse(await readFile(packagePath, "utf8"));
  const scripts = manifest.scripts ?? {};
  const wanted = {
    "decorator:sync": "ucsd-decorator-kit sync",
    "decorator:check": "ucsd-decorator-kit check",
    "decorator:drift": "ucsd-decorator-kit drift",
    "decorator:verify": "ucsd-decorator-kit verify",
  };
  let changed = false;
  for (const [name, value] of Object.entries(wanted)) {
    if (scripts[name]) continue;
    scripts[name] = value;
    changed = true;
  }
  if (!changed) return;
  manifest.scripts = scripts;
  await writeFile(packagePath, `${JSON.stringify(manifest, null, 2)}\n`);
  report.wrote.push("package.json (scripts)");
}

/**
 * Add this kit's Stop hook and permission guards to .claude/settings.json
 * without disturbing anything else already there.
 *
 * Unlike CLAUDE.md or dependabot.yml, this file is not exclusively this
 * kit's to write — a project may already have its own hooks or permissions
 * in it. `put()`'s overwrite-or-skip semantics are wrong here: skipping
 * would silently install nothing into a project that already has *some*
 * settings.json, and forcing would clobber whatever else was there. So this
 * reads, merges by matching each entry's own content (idempotent — running
 * `add --with-hook` twice does not duplicate anything), and writes. Like the
 * CI workflow it runs alongside, it is install-once, not tracked in
 * decorator-kit.json's `manages` list — `sync` never touches it.
 *
 * Three things get merged in:
 *
 *   - The Stop hook: `npx ucsd-decorator-kit verify` on Stop, backgrounded via
 *     `asyncRewake` so it never blocks the turn from ending, but if it finds a
 *     regression the agent is woken back up with the findings fed back as
 *     context — the exit-code-2 translation (`|| exit 2`) is what asyncRewake
 *     keys on.
 *   - `permissions.deny` on Edit/Write of the three chrome `*.local.json`
 *     files — a hard block, matching rules/00-canvas.md's unconditional "never
 *     create or edit" language for the same files.
 *   - `permissions.ask` on any Bash command matching `--accept` — forces
 *     explicit human approval in Claude Code's own UI before it runs, on top
 *     of (not instead of) the CLI-level gate in checks/chrome-contract.mjs,
 *     which holds even for a project that never installs this template.
 *
 * See templates/claude-settings.json and checks/README.md.
 */
async function installClaudeSettingsHook() {
  const template = JSON.parse(await readFile(path.join(TEMPLATES, "claude-settings.json"), "utf8"));
  const [stopGroup] = template.hooks.Stop;
  const command = stopGroup.hooks[0].command;

  const absolute = path.join(cwd, CLAUDE_SETTINGS);
  const existingRaw = await readFile(absolute, "utf8").catch(() => null);
  let settings = {};
  if (existingRaw !== null) {
    try {
      settings = JSON.parse(existingRaw);
    } catch (error) {
      throw new Error(`${CLAUDE_SETTINGS} is not valid JSON: ${error.message}`);
    }
  }

  let changed = false;

  settings.hooks ??= {};
  settings.hooks.Stop ??= [];
  const hookInstalled = settings.hooks.Stop.some((group) => group.hooks?.some((hook) => hook.command === command));
  if (!hookInstalled) {
    settings.hooks.Stop.push(stopGroup);
    changed = true;
  }

  for (const key of ["deny", "ask"]) {
    const wanted = template.permissions?.[key] ?? [];
    if (!wanted.length) continue;
    settings.permissions ??= {};
    settings.permissions[key] ??= [];
    for (const rule of wanted) {
      if (settings.permissions[key].includes(rule)) continue;
      settings.permissions[key].push(rule);
      changed = true;
    }
  }

  if (!changed) {
    report.skipped.push(`${CLAUDE_SETTINGS} (chrome gate hook and permissions already present)`);
    return;
  }

  await mkdir(path.dirname(absolute), { recursive: true });
  await writeFile(absolute, `${JSON.stringify(settings, null, 2)}\n`);
  report[existingRaw === null ? "wrote" : "refreshed"].push(CLAUDE_SETTINGS);
}

/**
 * Install dev dependencies, reporting failure rather than aborting.
 *
 * A registry that is unreachable — or a kit version that is not published yet —
 * must not take down the rest of the scaffold. The rule files are correct either
 * way, and abandoning half a scaffold is worse than finishing it and saying what
 * is missing.
 */
function install(packages) {
  console.log(`Installing ${packages.join(" ")}…`);
  try {
    execFileSync("npm", ["install", "--save-dev", ...packages], { cwd, stdio: "inherit" });
    return true;
  } catch {
    console.log(`  could not install ${packages.join(" ")}.`);
    return false;
  }
}

async function decoratorSourcePresent() {
  if (await exists(path.join(cwd, "node_modules", DECORATOR_PACKAGE))) return `node_modules/${DECORATOR_PACKAGE}`;
  if (await exists(path.join(cwd, "vendor/decorator-5"))) return "vendor/decorator-5";
  if (await exists(path.join(cwd, "core-template"))) return "core-template";
  return null;
}

function printReport() {
  for (const entry of report.wrote) console.log(`  wrote      ${entry}`);
  for (const entry of report.refreshed) console.log(`  refreshed  ${entry}`);
  for (const entry of report.skipped) console.log(`  skipped    ${entry} (already exists — \`sync\` updates managed files)`);
  for (const entry of report.refused) {
    console.log(`  refused    ${entry}`);
    console.log("");
    console.log(`  ${entry} is this kit's name for its generic rules, and also the`);
    console.log("  conventional name for a repository's own agent contract. Yours is the");
    console.log("  more specific document, so the kit will not write over it — not with");
    console.log("  --force either. The same rules are in CLAUDE.md, .cursorrules and");
    console.log("  .github/copilot-instructions.md; for a tool that reads AGENTS.md, keep");
    console.log("  a decorator-kit checkout beside this project and read its copy there.");
  }
  if (!report.wrote.length && !report.refreshed.length && !report.skipped.length && !report.refused.length) {
    console.log("  nothing to do — everything is already current.");
  }
}

// ── commands ──────────────────────────────────────────────────────────────

async function init() {
  const entries = (await readdir(cwd)).filter((entry) => !GREENFIELD_OK.has(entry));
  if (entries.length) {
    console.error(`${relative(cwd)} already looks like a project — it contains ${entries.slice(0, 4).join(", ")}${entries.length > 4 ? `, and ${entries.length - 4} more` : ""}.`);
    console.error("");
    console.error("`init` is for an empty directory: it writes AGENTS.md, adds dependencies,");
    console.error("and drops in CI, which is the wrong thing to do to a project that already");
    console.error("has its own. Use `add` instead — it installs the rules and the skill and");
    console.error("leaves everything else alone:");
    console.error("");
    console.error("  npx ucsd-decorator-kit add");
    process.exitCode = 1;
    return;
  }

  if (!(await exists(path.join(cwd, "package.json")))) {
    execFileSync("npm", ["init", "-y"], { cwd, stdio: "ignore" });
    report.wrote.push("package.json");
  }
  // Two separate installs so one failure does not mask the other. The Decorator
  // is what agents read; the kit is what `sync` and `check` run from later.
  const decoratorInstalled = install([DECORATOR_PACKAGE]);
  const kitInstalled = install([kitPackage.name]);

  const outputs = await renderFor(true);
  for (const [relativePath, contents] of outputs) await put(relativePath, contents, { force: true });
  await publishSkill();
  await put(".github/dependabot.yml", await readFile(path.join(TEMPLATES, "dependabot.yml"), "utf8"));
  await put(".github/workflows/decorator.yml", await readFile(path.join(TEMPLATES, "decorator.yml"), "utf8"));
  await installClaudeSettingsHook();
  await addScripts();
  await writeManifest([...outputs.keys(), SKILL_DEST]);
  report.wrote.push(MANIFEST);

  console.log("");
  printReport();
  console.log("");
  if (decoratorInstalled) {
    console.log("Done. The Decorator is on disk at");
    console.log(`  node_modules/${DECORATOR_PACKAGE}/dist/templates/`);
  } else {
    console.log(`${DECORATOR_PACKAGE} is NOT installed, so agents have no local markup to`);
    console.log("read and the rules point at a path that does not exist. Fix that first:");
    console.log("");
    console.log(`  npm install --save-dev ${DECORATOR_PACKAGE}`);
  }
  if (!kitInstalled) {
    console.log("");
    console.log(`${kitPackage.name} is not installed here, so the decorator:* npm scripts`);
    console.log("will not resolve. Run the commands through npx instead:");
    console.log("");
    console.log("  npx ucsd-decorator-kit@latest sync");
    console.log("  npx ucsd-decorator-kit@latest check");
  }
  console.log("");
  console.log("Open your AI tool in this directory and describe the site you want. It will");
  console.log("ask which layout to start from — blank-slate, two-column, three-column or");
  console.log("homepage — because choosing one unasked is the kind of decision this kit");
  console.log("exists to prevent.");
}

async function add() {
  const outputs = await renderFor(false);
  for (const [relativePath, contents] of outputs) await put(relativePath, contents);
  await publishSkill();

  // The rule set has four targets and `add` writes three. Say so every time,
  // rather than leaving someone to notice a missing file and wonder whether the
  // install half-failed. `put()` guards the same filename independently.
  report.refused.push(PROJECT_CONTRACT);

  if (has("with-ci")) {
    await put(".github/dependabot.yml", await readFile(path.join(TEMPLATES, "dependabot.yml"), "utf8"));
    await put(".github/workflows/decorator.yml", await readFile(path.join(TEMPLATES, "decorator.yml"), "utf8"));
  }
  if (has("with-hook")) {
    await installClaudeSettingsHook();
  }
  if (has("with-decorator")) {
    install([DECORATOR_PACKAGE]);
    await addScripts();
  }

  const managed = [...outputs.keys(), SKILL_DEST];
  const existing = await readManifest();
  await writeManifest(managed);
  if (!existing) report.wrote.push(MANIFEST);

  console.log("");
  printReport();

  const source = await decoratorSourcePresent();
  console.log("");
  if (source) {
    console.log(`Decorator source found at ${source}/ — the rules point agents there.`);
  } else {
    console.log("No Decorator source on disk. Agents will have nothing local to read from,");
    console.log("which is the failure this kit exists to prevent. Either:");
    console.log("");
    console.log("  npx ucsd-decorator-kit add --with-decorator   add it to package.json");
    console.log("  node <kit>/scripts/pin-decorator.mjs          pin vendor/decorator-5/");
  }
  if (!has("with-ci")) {
    console.log("");
    console.log("CI was not touched. `add --with-ci` writes a Dependabot config and a");
    console.log("workflow that runs `check` on pull requests and watches upstream weekly.");
  }
  if (!has("with-hook")) {
    console.log("");
    console.log("No Claude Code hook installed. `add --with-hook` adds a Stop hook that runs");
    console.log("`verify` in the background after each turn and wakes the agent back up — not");
    console.log("the user, and not blocking anything meanwhile — if it finds a regression. It");
    console.log("also adds permission rules: denying edits to the chrome *.local.json files,");
    console.log("and requiring your approval before any Bash command matching --accept.");
  }
}

async function managedFiles() {
  const manifest = await readManifest();
  if (!manifest) {
    throw new Error(`No ${MANIFEST} here. Run \`npx ucsd-decorator-kit add\` first.`);
  }
  return manifest;
}

async function sync() {
  const manifest = await managedFiles();
  const managesContract = manifest.manages.includes(PROJECT_CONTRACT);
  const outputs = await renderFor(managesContract);
  for (const [relativePath, contents] of outputs) {
    if (!manifest.manages.includes(relativePath)) continue;
    await put(relativePath, contents, { force: true, allowContract: managesContract });
  }
  if (manifest.manages.includes(SKILL_DEST)) await publishSkill();
  await writeManifest(manifest.manages);
  console.log("");
  printReport();
  console.log("");
  console.log(`Managed files are current with ucsd-decorator-kit@${VERSION}.`);
}

async function check() {
  const manifest = await managedFiles();
  const outputs = await renderFor(manifest.manages.includes(PROJECT_CONTRACT));
  const stale = [];

  for (const [relativePath, contents] of outputs) {
    if (!manifest.manages.includes(relativePath)) continue;
    const current = await readFile(path.join(cwd, relativePath), "utf8").catch(() => null);
    if (current !== contents) stale.push(relativePath);
  }

  if (manifest.manages.includes(SKILL_DEST)) {
    const destination = path.join(cwd, SKILL_DEST);
    if (!(await exists(destination))) stale.push(`${SKILL_DEST}/`);
    else {
      const source = (await walk(SKILL_SOURCE, SKILL_SOURCE)).sort();
      const published = (await walk(destination, destination)).sort();
      let differs = source.length !== published.length || source.some((file, i) => file !== published[i]);
      if (!differs) {
        for (const file of source) {
          const [a, b] = await Promise.all([
            readFile(path.join(SKILL_SOURCE, file), "utf8"),
            readFile(path.join(destination, file), "utf8"),
          ]);
          if (a !== b) {
            differs = true;
            break;
          }
        }
      }
      if (differs) stale.push(`${SKILL_DEST}/`);
    }
  }

  if (stale.length) {
    console.error(`These files are out of date with ucsd-decorator-kit@${VERSION}:`);
    for (const entry of stale) console.error(`  ${entry}`);
    console.error("");
    console.error("Run `npx ucsd-decorator-kit sync` and commit the result.");
    process.exitCode = 1;
    return;
  }
  console.log(`${manifest.manages.length} managed paths are current with ucsd-decorator-kit@${VERSION}.`);
}

async function drift() {
  // A project that pins into vendor/ has a lockfile to compare against.
  if (await exists(path.join(cwd, "vendor/decorator-5/decorator.lock.json"))) {
    execFileSync(process.execPath, [path.join(KIT_ROOT, "scripts/pin-decorator.mjs"), "--check"], {
      cwd,
      stdio: "inherit",
    });
    return;
  }

  const installed = path.join(cwd, "node_modules", DECORATOR_PACKAGE, "package.json");
  if (!(await exists(installed))) {
    console.error(`Neither vendor/decorator-5/ nor node_modules/${DECORATOR_PACKAGE}/ is here.`);
    console.error("Nothing to compare against — install the Decorator first.");
    process.exitCode = 1;
    return;
  }
  const local = JSON.parse(await readFile(installed, "utf8")).version;
  const response = await fetch(`https://registry.npmjs.org/${DECORATOR_PACKAGE}/latest`, {
    headers: { Accept: "application/json", "User-Agent": "ucsd-decorator-kit-drift" },
    signal: AbortSignal.timeout(60000),
  });
  if (!response.ok) throw new Error(`npm registry responded ${response.status}`);
  const latest = (await response.json()).version;
  if (local === latest) {
    console.log(`${DECORATOR_PACKAGE} is current (${local}).`);
    console.log("");
    console.log("Note: this only sees published releases. A push to UCSD/Decorator or a");
    console.log("cdn.ucsd.edu deploy without an npm publish will not show up here.");
    return;
  }
  console.error(`${DECORATOR_PACKAGE} moved upstream: installed ${local}, latest ${latest}.`);
  console.error(`Run \`npm install --save-dev ${DECORATOR_PACKAGE}@${latest}\` and review the diff.`);
  process.exitCode = 1;
}

// `check` above verifies this kit's own generated files (CLAUDE.md and
// friends) are current — a different question from whether a project's built
// chrome is correct, which is what `verify` answers. Same word for both would
// be the same confusion this command exists to resolve, so it gets its own.
//
// This is a thin wrapper: checks/chrome-contract.mjs runs standalone, reading
// nothing but files already on disk (contracts/, decorator-kit.json, the
// project's own *.html/*.css/*.js). `verify` exists for symmetry with
// sync/check/drift, not because the gate needs the CLI to function — see
// checks/README.md.
async function verify() {
  const passthrough = argv.filter((entry) => entry !== "verify");
  try {
    execFileSync(process.execPath, [path.join(KIT_ROOT, "checks/chrome-contract.mjs"), ...passthrough], {
      cwd,
      stdio: "inherit",
    });
  } catch (error) {
    // chrome-contract.mjs already printed everything useful via stdio:
    // "inherit" — just propagate its exit code, not a second generic
    // "Command failed" line on top of its own detailed findings.
    process.exitCode = error.status ?? 1;
  }
}

